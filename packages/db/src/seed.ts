function makeVideo(ext: "mp4" | "webm", src: string): Buffer | null {
  const dir = mkdtempSync(path.join(tmpdir(), "seed-"));
  const out = path.join(dir, `v.${ext}`);
  const codec = ext === "mp4" ? ["-c:v", "libx264", "-pix_fmt", "yuv420p"] : ["-c:v", "libvpx-vp9", "-b:v", "1M"];
  const r = spawnSync("ffmpeg", ["-y", "-f", "lavfi", "-i", `${src}=size=1280x720:rate=30`, "-f", "lavfi",
    "-i", "sine=frequency=440:duration=6", "-t", "6", ...codec, "-c:a", ext === "mp4" ? "aac" : "libopus", out]);
  try {
    return r.status === 0 ? readFileSync(out) : null;
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

async function addMedia(uploaderId: string, filename: string, mime: string, body: Buffer, description: string, alt: string) {
  const slug = slugify(filename);
  const [existing] = await db.select({ id: media.id }).from(media).where(eq(media.slug, slug));
  if (existing) return;
  const id = crypto.randomUUID();
  const key = `originals/${id}/${filename}`;
  await putObject({ Key: key, Body: body, ContentType: mime });
  await db.insert(media).values({
    id, uploaderId, kind: mime.startsWith("video") ? "video" : "image", filename, slug,
    originalKey: key, mimeType: mime, size: body.length, description, altText: alt,
    license: "CC0-1.0", source: "Generated by the seed script",
  });
  await enqueueMedia({ mediaId: id });
  console.log("queued media", filename);
}

