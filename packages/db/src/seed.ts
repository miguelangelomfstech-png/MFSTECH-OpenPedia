async function main() {
  await ensureBucket();
  const hash = await bcrypt.hash(adminPassword, 12);
  await db.insert(users).values({
    name: "Admin", email: "admin@example.com", passwordHash: hash, role: "bureaucrat",
    createdAt: new Date(Date.now() - 30 * 86400_000), editCount: 100,
  }).onConflictDoNothing();
  const [admin] = await db.select().from(users).where(eq(users.email, "admin@example.com"));
  const actor: Actor = { userId: admin.id, role: "bureaucrat", autoconfirmed: true, blocked: false, ipHash: null };

  await addMedia(admin.id, "Solar_system.svg", "image/svg+xml", Buffer.from(svg("#0b1d51", "#7b2ff7", "Solar System")), "Seed illustration.", "Gradient illustration");
  await addMedia(admin.id, "Mountain.svg", "image/svg+xml", Buffer.from(svg("#0f766e", "#38bdf8", "Mountain")), "Seed illustration.", "Teal gradient");
  await addMedia(admin.id, "Circuit.svg", "image/svg+xml", Buffer.from(svg("#4c1d95", "#db2777", "Circuit")), "Seed illustration.", "Purple gradient");

  const mp4 = makeVideo("mp4", "testsrc2");
  const webm = makeVideo("webm", "smptebars");
  if (mp4 && webm) {
    await addMedia(admin.id, "Test_pattern.mp4", "video/mp4", mp4, "Generated 720p test pattern.", "Colourful test pattern");
    await addMedia(admin.id, "Color_bars.webm", "video/webm", webm, "Generated SMPTE color bars.", "Color bars");
  } else {
    console.warn("ffmpeg not found on host: skipping seed videos (install ffmpeg and re-run).");
  }

  for (const a of ARTICLES) {
    const ns = a.ns ?? "main";
    const slug = slugify(a.title);
    const [exists] = await db.select({ id: articles.id }).from(articles)
      .where(eq(articles.slug, slug));
    if (exists && !a.ns) continue;
    try {
      const res = await saveRevision({ namespace: ns, title: a.title, content: a.body, summary: "Seed", actor });
      if (a.featured) await db.update(articles).set({ featured: true, featuredAt: new Date() }).where(eq(articles.id, res.articleId));
      console.log("saved", ns, a.title);
    } catch (e) {
      console.log("skip", a.title, (e as Error).message);
    }
  }
  console.log(`Seed complete. Admin login: admin@example.com / ${adminPassword}`);
}

main().catch((e) => { console.error(e); process.exitCode = 1; }).finally(async () => {
  await pool().end();
  redis().disconnect();
  process.exit(process.exitCode ?? 0);
});
